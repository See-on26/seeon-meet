const PLACEHOLDER_PATTERN = /\{(\w+)\}/g;

// 고른 언어에 키가 없으면 한국어, 한국어에도 없으면 키 그대로 보인다(빠진 키가 화면에서 바로 드러나게).
// 넘기지 않은 자리표는 그대로 둔다.
export function createUiText({ getLanguage }) {
  return function t(key, params = {}) {
    const textMap = UI_TEXT_MAP[getLanguage()] || UI_TEXT_MAP[DEFAULT_UI_LANGUAGE];
    const template = textMap[key] ?? UI_TEXT_MAP[DEFAULT_UI_LANGUAGE][key] ?? key;
    return template.replace(PLACEHOLDER_PATTERN, (placeholder, name) => (
      Object.hasOwn(params, name) ? String(params[name]) : placeholder
    ));
  };
}

// 모듈의 기본 번역기. t 를 받지 않으면 지금처럼 한국어로 보인다.
export const defaultUiText = createUiText({ getLanguage: () => DEFAULT_UI_LANGUAGE });

// index.html 의 고정 글자는 data-ui-text* 에 키를 적어 두고, 시작할 때와 캡션 언어가 바뀔 때 다시 입힌다.
// data-ui-text 를 단 요소는 글자만 담는다(textContent 로 바꾸므로 안쪽 태그는 사라진다).
const DOM_ATTRIBUTE_BINDING_LIST = [
  { selector: '[data-ui-text-aria-label]', datasetKey: 'uiTextAriaLabel', attribute: 'aria-label' },
  { selector: '[data-ui-text-title]', datasetKey: 'uiTextTitle', attribute: 'title' },
  { selector: '[data-ui-text-placeholder]', datasetKey: 'uiTextPlaceholder', attribute: 'placeholder' },
];

export function applyUiTextToDom({ root, t }) {
  for (const element of root.querySelectorAll('[data-ui-text]')) element.textContent = t(element.dataset.uiText);
  for (const { selector, datasetKey, attribute } of DOM_ATTRIBUTE_BINDING_LIST) {
    for (const element of root.querySelectorAll(selector)) element.setAttribute(attribute, t(element.dataset[datasetKey]));
  }
}
