const { buildOutputLanguageRuleList } = require('./output-language-rule');

// 구간에 담을 내용이 없을 때의 답. 빈 구간은 정상이라 에이전트가 이 답을 빈 글로 바꾼다.
const SEGMENT_NONE_TOKEN = 'NONE';
const NONE_TOKEN_KEEP_RULE = `담을 내용이 없을 때의 "${SEGMENT_NONE_TOKEN}"은 번역하지 말고 그대로 출력한다.`;

// 회의 중에 구간마다 짧게 요약해 두고, 회의 뒤에 이 요약들을 이어 회의 전체 요약을 만든다.
// 재료가 길 수 있어 꼭 지킬 규칙을 재료 뒤에 한 번 더 둔다.
function buildSegmentSummaryPrompt({ materialText, language = 'ko' }) {
  return [
    '너는 시각장애인 참석자를 위한 회의 요약의 한 구간을 쓴다.',
    '독자는 회의에 함께 있었지만 공유 화면을 볼 수 없었다. 이 구간 요약들은 나중에 시간순으로 이어 회의 전체 요약의 재료가 된다.',
    '재료는 회의 한 구간의 기록이다. 화면 정보, 오간 말, 들려준 해설, 질문·답 가운데 있는 것이 담겨 있다.',
    '',
    '■ 쓸 것',
    '  · 그 자료가 말하는 결론과 오간 말의 요지를 쓴다. 결정된 것이나 하기로 한 일이 있으면 그것도 쓴다.',
    '  · 자료가 무엇이었는지가 아니라 그 자료가 말해 주는 것을 쓴다. 화면의 배치·위치는 쓰지 않는다.',
    '  · 평문 3~5문장, 600자 안으로 쓴다.',
    '',
    '■ 지킬 것',
    '  · 재료에 없는 내용·숫자를 쓰지 않는다. 발화가 불분명하면 단정하지 않는다.',
    '  · 재료가 말하지 않은 인과(이로 인해·때문에·그 결과)로 사실을 잇지 않는다.',
    '  · 한 항목의 값·수식어를 다른 항목에 옮겨 붙이지 않는다.',
    '  · 지난 답변·과거 계획·전망을 이번 회의의 결정이나 지금의 사실처럼 쓰지 않는다.',
    '  · 회의의 목적·배경은 재료에 나온 것만 쓴다.',
    '  · 값과 단위는 재료에 적힌 그대로 쓴다. 단위를 바꾸거나 값을 어림하지 않는다.',
    '  · 누가 말했는지 쓰지 않는다.',
    '  · 표·마크다운·목록 기호·도형 기호를 쓰지 않는다. 문장으로만 쓴다.',
    `  · 담을 내용이 없으면(재료가 비었거나 인사·잡담뿐이면) 다른 말 없이 정확히 ${SEGMENT_NONE_TOKEN} 한 단어만 출력한다.`,
    '',
    '■ 재료',
    materialText,
    '',
    `위 재료로 구간 요약 문장만 출력한다. 머리말을 붙이지 않는다. 재료에 없는 내용·숫자를 쓰지 않고, 담을 내용이 없으면 정확히 ${SEGMENT_NONE_TOKEN} 만 출력한다.`,
    ...buildOutputLanguageRuleList({ language, detailLineList: [NONE_TOKEN_KEEP_RULE] }),
  ].join('\n');
}

module.exports = { buildSegmentSummaryPrompt, SEGMENT_NONE_TOKEN };
